/**
 * Generates `styles/tokens/modules.css` from the ZeyOS module configuration.
 *
 * Run `node tools/build-module-tokens.js` after editing `src/zeyos/modules.js`. The unit test
 * `tests/unit/zeyos-modules.test.js` compares the checked-in file against this generator's
 * output, so the two can never drift apart unnoticed.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

import { moduleAliases, zeyosModules } from '../src/zeyos/modules.js';

const root = resolve(import.meta.dirname, '..');
const target = resolve(root, 'styles/tokens/modules.css');

/**
 * Renders the module colour token sheet.
 * @returns {string} CSS source, newline-terminated.
 */
export function renderModuleTokens() {
  const lines = [
    '/* ZeyOS module identity colours.',
    '   Generated by tools/build-module-tokens.js from src/zeyos/modules.js — do not edit by hand.',
    '   Colours come from the ZeyOS runtime palette where ZeyOS defines one, and are Zx defaults',
    '   for the rest. `--zx-module-fg-*` are the two glyph foregrounds the palette was measured',
    '   against; moduleChip() picks the higher-contrast one per module. */',
    ':root {',
    '  --zx-module-fg-light: #ffffff;',
    '  --zx-module-fg-dark: #141414;',
    ''
  ];

  for (const key of Object.keys(zeyosModules).sort()) {
    lines.push(`  --zx-module-${key}: ${zeyosModules[key].color};`);
  }

  lines.push('', '  /* Entity, API resource, and legacy gx names resolving to a module colour. */');
  for (const key of Object.keys(moduleAliases).sort()) {
    lines.push(`  --zx-module-${key}: var(--zx-module-${moduleAliases[key]});`);
  }

  lines.push('}', '');
  return lines.join('\n');
}

/**
 * Reads the checked-in token sheet.
 * @returns {Promise<string>} File contents.
 */
export function readModuleTokens() {
  return readFile(target, 'utf8');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await writeFile(target, renderModuleTokens());
  console.log(`Wrote ${target}`);
}
